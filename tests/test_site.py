import pandas as pd
import pytest

from pwl import cli
from pwl.models import lagged
from pwl.site import REPORT_CLAIMS, _within_year_costs, implied_points_per_10usd

DOCS = Path(__file__).parents[1] / "docs"
HTML = (DOCS / "index.html").read_text(encoding="utf-8")
PERSONAL_SITE = "https://aeternifrigus.netlify.app"


def test_implied_oil_effect_comes_from_the_reports_own_anchor_numbers():
    # 52% at 70 USD down to 38% at 90 USD is 14 points over 20 USD, so 7 points per 10 USD.
    assert implied_points_per_10usd(REPORT_CLAIMS) == 7.0


def test_within_year_costs_measures_q2_to_q4_changes():
    quarters = ["2022Q2", "2022Q4", "2023Q2", "2023Q4", "2024Q2"]  # 2024 has no Q4 and is skipped
    frame = pd.DataFrame(
        {
            "quarter": quarters,
            "net_revenue_cr": [100.0, 50.0, 200.0, 120.0, 300.0],
            "opex_cr": [40.0, 36.0, 80.0, 72.0, 100.0],
        }
    )
    result = _within_year_costs(frame)
    assert [y["year"] for y in result["years"]] == [2022, 2023]
    assert result["years"][0]["sales_change_pct"] == -50.0
    assert result["years"][0]["opex_change_pct"] == -10.0
    assert result["years"][0]["opex_ratio_q4"] == 72.0
    assert result["median_sales_change_pct"] < result["median_opex_change_pct"] < 0


def test_within_year_costs_handles_data_without_pairs():
    frame = pd.DataFrame({"quarter": ["2022Q1"], "net_revenue_cr": [1.0], "opex_cr": [1.0]})
    assert _within_year_costs(frame) == {"years": []}


@pytest.fixture
def built(runner, tmp_path, monkeypatch):
    monkeypatch.setattr(lagged, "ALPHAS", (0.1, 10.0, 1000.0))  # structure matters here, not tuning
    out = tmp_path / "data.js"
    result = runner.invoke(cli.app, ["site", "--out", str(out)])
    assert result.exit_code == 0, result.output
    text = out.read_text(encoding="utf-8")
    assert text.startswith("// Generated by `pwl site`")
    payload = (
        text[text.index("window.SITE_DATA = ") + len("window.SITE_DATA = ") :].rstrip().rstrip(";")
    )
    return json.loads(payload)


def test_site_data_is_built_from_the_repositorys_own_outputs(built):
    features = pd.read_csv(cli.FEATURES_CSV)
    assert len(built["quarters"]) == len(features)
    assert built["report_claims"]["implied_points_per_10usd"] == 7.0
    assert len(built["claims"]) == 15
    assert set(built["backtest"]["ablation"]) == {
        "seasonal_only",
        "seasonal_plus_oil",
        "seasonal_plus_weather",
        "all",
    }
    series = built["backtest"]["series"]
    assert len(series) >= 20 and {"quarter", "actual", "model", "seasonal_naive"} <= set(series[0])
    assert built["model"]["effect_per_10usd"]["estimate"] < 0


def test_site_data_supports_the_operating_leverage_story(built):
    costs = built["seasonal_costs"]
    assert len(costs["years"]) >= 5
    # Sales fall much more than costs from Q2 to Q4, which is the whole point of the chart.
    assert costs["median_sales_change_pct"] < costs["median_opex_change_pct"] < 0
    assert costs["median_opex_ratio_q4"] > costs["median_opex_ratio_q2"]


def test_site_command_needs_the_model_outputs(runner, tmp_path, monkeypatch):
    monkeypatch.setattr(cli, "REPORTS", tmp_path / "empty_reports")
    result = runner.invoke(cli.app, ["site", "--out", str(tmp_path / "data.js")])
    assert result.exit_code == 2


def test_page_loads_nothing_from_other_sites():
    assert not re.search(r"<script[^>]+src=[\"']https?:", HTML)
    assert not re.search(r"<link[^>]+href=[\"']https?:", HTML)
    assert not re.search(r"<img[^>]+src=[\"']https?:", HTML)
    assert '<script src="data.js"></script>' in HTML
    assert (DOCS / ".nojekyll").exists()


def test_every_element_the_script_uses_exists_in_the_page():
    ids = set(re.findall(r'id="([\w-]+)"', HTML))
    used = set(re.findall(r'\$\("([\w-]+)"\)', HTML)) | set(re.findall(r'chart\("([\w-]+)"', HTML))
    assert used, "expected the script to reference elements"
    assert used - ids == set()


def test_byline_links_to_the_authors_site_safely():
    links = re.findall(r'<a[^>]+href="' + re.escape(PERSONAL_SITE) + r'"[^>]*>', HTML)
    assert len(links) >= 3  # nav, byline under the title, footer
    assert all('target="_blank"' in tag and 'rel="noopener noreferrer"' in tag for tag in links)
    assert "By <a" in HTML


def test_page_has_no_em_dashes():
    assert "\u2014" not in HTML
